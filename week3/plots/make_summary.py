"""week3/results/week3_summary.md (every Week 3 headline number), plus the
derived noise_model_retention.csv and deck_numbers.json (numbers the slides use)."""
import json

import numpy as np
import pandas as pd

from bp.config import SHOT_GRID, TASK_ITERS, TASK_TARGET
from bp.data import results_dir

R = results_dir(3)
out = []
w = out.append


def table(header, rows):
    w("| " + " | ".join(header) + " |")
    w("|" + "---|" * len(header))
    for r in rows:
        w("| " + " | ".join(str(x) for x in r) + " |")
    w("")


def g3(x):
    return f"{x:.3g}"


w("# Week 3 results summary")
w("")
w("Generated by `week3/plots/make_summary.py` from the CSV files in `week3/results/`.")
w("")

# ------------------------------------------------------------------ Q1 variance level
sb = pd.read_csv(R / "shot_budget.csv")
w("## Q1: shot budget for a measurable gradient (HEA, L = ⌈log₂ n⌉, θ₁, uniform init)")
w("")
w("N* = shots per circuit at which the parameter-shift shot noise equals the gradient variance "
  "(SNR = 1). Worst case = the same with a single-shot variance of 1/4 per circuit. 95% bootstrap intervals.")
w("")
rows = []
for n in sorted(sb.n.unique()):
    r = [n]
    for c in ("global", "local"):
        s = sb[(sb.n == n) & (sb.cost == c)].iloc[0]
        r += [f"{g3(s.n_star)} [{g3(s.n_star_lo)}, {g3(s.n_star_hi)}]", g3(s.n_star_worst)]
    rows.append(r)
table(["n", "N* global", "worst case global", "N* local", "worst case local"], rows)
for c in ("global", "local"):
    d = sb[(sb.cost == c) & (sb.n >= 4)]
    b = np.polyfit(d.n, np.log(d.n_star), 1)[0]
    w(f"* {c}: N* grows ×{np.exp(2 * b):.2f} per 2 qubits (fit over n = 4…14).")
g = sb[sb.cost == "global"]
over = (g.n_star_worst / g.n_star).to_numpy()
w(f"* The worst-case estimate overstates the global budget by {over[1]:.0f}× at n = 4, rising to "
  f"{over[-1]:,.0f}× at n = {int(g.n.max())}.")
for N in SHOT_GRID:
    ok = {c: sb[(sb.cost == c) & (sb[f"snr_{N}"] >= 1)].n.max() for c in ("global", "local")}
    w(f"* {N} shots: SNR ≥ 1 up to n = {ok['global']} (global) and n = {ok['local']} (local, every n tested).")
w("")

# ------------------------------------------------------------------ Q1 training
numbers = {}
tp = R / "shot_training_final.csv"
if tp.exists():
    tf = pd.read_csv(tp)
    w(f"## Q1: teacher-task training at each shot budget ({TASK_ITERS} Adam steps, uniform init)")
    w("")
    w(f"Each cell: seeds reaching C_G ≤ {TASK_TARGET}, median steps to target (> {TASK_ITERS} if fewer "
      "than half reach it), median final C_G.")
    w("")

    def cell(s):
        it = np.median(s.iters_to_target.fillna(np.inf))
        return (f"{int(s.reached.sum())}/{len(s)}, {'> ' + str(TASK_ITERS) if not np.isfinite(it) else f'{it:.0f}'}, "
                f"{np.median(s.C_G_final):.3f}")
    rows = []
    for (n, c), d in tf.groupby(["n", "cost"]):
        rows.append([n, c] + [cell(d[d.shots == N]) if (d.shots == N).any() else "–" for N in SHOT_GRID])
    table(["n", "training cost"] + [f"{N} shots" for N in SHOT_GRID], rows)
    t12 = tf[tf.n == 12]
    if len(t12):
        g12 = t12.groupby(["cost", "shots"])
        rate = g12.reached.mean()
        steps = g12.iters_to_target.apply(lambda s: np.median(s.fillna(np.inf)))
        gl = {N: rate.get(("global", N), np.nan) for N in (1024, 10000)}
        lo = {N: rate.get(("local", N), np.nan) for N in (1024, 10000)}
        sg = {N: steps.get(("global", N), np.nan) for N in (1024, 10000)}
        sl = {N: steps.get(("local", N), np.nan) for N in (1024, 10000)}
        k12 = int(g12.size().min())
        r_lo = tf[tf.shots == 1024].groupby(["n", "cost"]).reached.mean().min()
        numbers["stat3_num"] = f"{sg[1024]:.0f} → {sg[10000]:.0f}"
        numbers["stat3_label"] = "steps to target at 12 qubits (global), 1024 → 10k shots"
        numbers["q1_answer"] = ("Local: 11–29 shots up to 14 qubits; global: ×3.5 per 2 qubits (790 at 12). "
                                "In training to 12 qubits, 1024 shots suffice for both; 10,000 halve the steps.")
        numbers["slide7_notes"] = (
            "Question one, the shot budget, treated as a hyperparameter. For each cost I computed how many shots per circuit are "
            "needed before the gradient signal is larger than the measurement noise. The local cost needs only 11 to 29 shots, "
            "even at 14 qubits. The global cost needs about 3.5 times more for every 2 extra qubits: 790 at 12 qubits and 3,740 "
            "at 14, far fewer than the usual worst-case estimate, because the noise of estimating a tiny probability is tiny too. "
            "Then I trained the teacher task at 256, 1024, 5000 and 10,000 shots. Up to 12 qubits, 1024 shots are already "
            f"enough for both costs; more shots mostly make training faster: at 12 qubits the global cost needs a median of "
            f"{sg[1024]:.0f} steps with 1024 shots and {sg[10000]:.0f} with 10,000 (local: {sl[1024]:.0f} and {sl[10000]:.0f}). "
            "That matches the prediction: 1024 shots only run out for the global cost between 12 and 14 qubits. "
            f"The 12-qubit point uses {k12} seeds per setting, so treat its success rates as indicative. (~1.5 min)")
        w(f"* n = 12 ({k12} seeds per cell): success rate global {gl[1024]:.0%} (1024 shots) → {gl[10000]:.0%} (10,000), "
          f"local {lo[1024]:.0%} → {lo[10000]:.0%}; median steps global {sg[1024]:.0f} → {sg[10000]:.0f}, "
          f"local {sl[1024]:.0f} → {sl[10000]:.0f}.")
        w(f"* With 1024 shots at least {r_lo:.0%} of seeds reach the target for every n ≤ 12 and both costs; extra shots "
          "mainly cut the number of steps. This matches the variance-level prediction (1024 shots give SNR ≥ 1 for the "
          "global cost up to n = 12).")
        w("")

# ------------------------------------------------------------------ Q2
val = pd.read_csv(R / "noise_model_validation.csv")
w("## Q2: analytical (Pauli-path) noise model vs. simulation")
w("")
w("The model is the exact average over uniform random angles (no sampling). Simulated values come from "
  "200–2000 random draws with 95% bootstrap intervals.")
w("")
rows = [[s, m, st, len(d), f"{d.inside_ci.mean():.0%}", f"{d.ratio.median():.3f}"]
        for (s, m, st), d in val.groupby(["source", "model", "stat"])]
table(["source", "noise", "statistic", "points", "model inside 95% CI", "median model / sim"], rows)
w("Points outside the interval are dominated by the heavy-tailed global-cost gradient at 200 draws "
  "(the percentile bootstrap undercovers there); the noiseless model is exact by construction and matches "
  "40,000-draw Monte Carlo to within its 1–3% error (tests/test_pauli_path.py).")
w("")

# paired retention: Var_noisy / Var_noiseless on the same draws
v2 = val[val.source == "week2_density"]
key = ["study", "n", "L", "cost", "stat"]
base = v2[v2.model == "noiseless"]
ret = []
for _, r in v2[v2.model != "noiseless"].iterrows():
    b = base[(base.study == r.study) & (base.n == r.n) & (base.L == r.L) & (base.cost == r.cost) & (base.stat == r.stat)].iloc[0]
    ret.append(dict(study=r.study, n=r.n, L=r.L, p2=r.p2, model=r.model, cost=r.cost, stat=r.stat,
                    keep_sim=r.sim / b.sim, keep_model=r.model_value / b.model_value))
ret = pd.DataFrame(ret)
ret["rel_err"] = ret.keep_model / ret.keep_sim - 1
ret.to_csv(R / "noise_model_retention.csv", index=False)
w("Fraction of the variance that survives the noise (same draws with and without noise), model vs. simulation:")
w("")
rows = []
for (m, c), d in ret[ret.stat == "var_mean"].groupby(["model", "cost"]):
    rows.append([m, c, f"{np.median(np.abs(d.rel_err)):.1%}", f"{np.abs(d.rel_err).max():.1%}"])
table(["noise", "cost", "median abs. error", "max abs. error"], rows)
pp = ret[(ret.study == "p") & (ret.stat == "var_mean") & (ret.model == "amplitude_damping")].sort_values("p2")
w("Amplitude damping, n = 6, L = 6: simulated retention vs. the model's unital part (the difference is the "
  "non-unital pull towards |0…0⟩):")
w("")
table(["p₂", "global sim", "global unital part", "local sim", "local unital part"],
      [[p, f"{d[d.cost == 'global'].keep_sim.iloc[0]:.3f}", f"{d[d.cost == 'global'].keep_model.iloc[0]:.3f}",
        f"{d[d.cost == 'local'].keep_sim.iloc[0]:.3f}", f"{d[d.cost == 'local'].keep_model.iloc[0]:.3f}"]
       for p, d in pp.groupby("p2")])

mp = pd.read_csv(R / "noise_model_map.csv")
piv = mp.pivot_table(index=["n", "L", "p2"], columns="cost", values="var_k").reset_index()
b0 = piv[piv.p2 == 0].set_index(["n", "L"])
piv["keep_G"] = [r["global"] / b0.loc[(r.n, r.L), "global"] for _, r in piv.iterrows()]
piv["keep_L"] = [r["local"] / b0.loc[(r.n, r.L), "local"] for _, r in piv.iterrows()]
piv["gap_growth"] = piv.keep_L / piv.keep_G
w("Regime map (model, depolarizing, θ₁): growth of the local/global variance gap, (Var_L/Var_G)_noisy / "
  "(Var_L/Var_G)_noiseless:")
w("")
Ls = sorted(piv.L.unique())
for p2 in (0.01, 0.03):
    w(f"p₂ = {p2}:")
    w("")
    table(["n"] + [f"L={L}" for L in Ls],
          [[n] + [f"{piv[(piv.n == n) & (piv.L == L) & (piv.p2 == p2)].gap_growth.iloc[0]:.2f}" for L in Ls]
           for n in sorted(piv.n.unique())])
w("Effective number of two-qubit noise events seen by each cost, N_eff = ln(retention) / (2 ln(1 − p₂)), "
  "at p₂ = 0.01 (the local cost's is the same for every n: its light cone):")
w("")
p1 = piv[piv.p2 == 0.01].copy()
for c, k in (("global", "keep_G"), ("local", "keep_L")):
    p1[c] = np.log(p1[k]) / (2 * np.log(1 - 0.01))
table(["n"] + [f"L={L}" for L in Ls],
      [[f"{n} {c}"] + [f"{p1[(p1.n == n) & (p1.L == L)][c].iloc[0]:.1f}" for L in Ls]
       for n in sorted(p1.n.unique()) for c in ("global", "local")])

(R / "week3_summary.md").write_text("\n".join(out), encoding="utf-8")
(R / "deck_numbers.json").write_text(json.dumps(numbers, indent=1, ensure_ascii=False), encoding="utf-8")
print("wrote week3/results/week3_summary.md, noise_model_retention.csv, deck_numbers.json")
