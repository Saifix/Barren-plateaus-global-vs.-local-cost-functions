"""week2/results/week2_summary.md: every Week 2 headline number, generated from the CSVs in
week2/results/ (and Run B's in week1/results/)."""
import numpy as np
import pandas as pd

from bp.config import HW_SHOTS, NOISE_P2, RUN_D_N, SHOTS_TRAIN, TASK_ITERS, TASK_SHOTS, TASK_TARGET
from bp.data import results_dir

R = results_dir(2)
out = []
w = out.append


def fmt(x, d=2):
    return f"{x:.{d}e}" if (abs(x) < 1e-2 or abs(x) >= 1e4) and x != 0 else f"{x:.{d}f}"


def ci(v, lo, hi, d=2):
    return f"{fmt(v, d)} [{fmt(lo, d)}, {fmt(hi, d)}]"


def table(header, rows):
    w("| " + " | ".join(header) + " |")
    w("|" + "---|" * len(header))
    for r in rows:
        w("| " + " | ".join(str(x) for x in r) + " |")
    w("")


w("# Week 2 results summary")
w("")
w("Generated by `week2/plots/make_summary.py` from the CSV files in `week2/results/`. "
  "Intervals are 95% percentile bootstrap intervals over parameter draws (1000 resamples) "
  "unless stated otherwise; ± values are standard deviations over seeds (and folds).")
w("")

# ------------------------------------------------------------------ H3 variance
iv = pd.read_csv(R / "init_variance.csv")
fits = pd.read_csv(R / "init_variance_fits.csv")
rat = pd.read_csv(R / "init_variance_ratios.csv")
w("## H3, part 1: initial gradient variance (identity-block HEA, D = ⌈log₂ n⌉)")
w("")
w("Circuit `ib_hea(n, D)`: one identity-compatible block of 2D rotation layers and 2(D−1) CZ layers. "
  "Target |ψ₀⟩ = V(θ*)†|0…0⟩ with a fresh teacher θ* per draw (shared across initializations). "
  "Var[∂C/∂θ₁], θ₁ = R_Y on qubit 1 in the first layer; 200 draws (2000 for n ≥ 10).")
w("")
rows = []
for n in sorted(iv.n.unique()):
    r = [n, int(iv[iv.n == n].D.iloc[0])]
    for cost in ("global", "local"):
        for init in ("uniform", "reduced", "identity"):
            s = iv[(iv.n == n) & (iv.cost == cost) & (iv.init == init) & (iv.scale == 1.0)].iloc[0]
            r.append(fmt(s.var_k))
    rows.append(r)
table(["n", "D", "C_G uniform", "C_G reduced", "C_G identity", "C_L uniform", "C_L reduced", "C_L identity"], rows)
w("Fitted decay rate b (log Var = a − b n, n = 4…14):")
w("")
rows = []
for init, scale in (("uniform", 1.0), ("reduced", 1.0), ("identity", 1.0), ("reduced", 0.5), ("reduced", 0.25)):
    r = [init if init != "reduced" else f"reduced, a = {scale:g}π/√L"]
    for cost in ("global", "local"):
        f = fits[(fits.init == init) & (fits.scale == scale) & (fits.cost == cost) & (fits.stat == "var_k")].iloc[0]
        r.append(ci(f.b, f.b_lo, f.b_hi))
    rows.append(r)
table(["initialization", "b, global", "b, local"], rows)
w("Variance ratio to uniform initialization at n ≥ 10 (H3 falsifier: neither scheme reaches 10× for C_G):")
w("")
rows = []
big = rat[(rat.n >= 10) & (rat.stat == "var_k")]
for _, s in big.sort_values(["cost", "init", "scale", "n"]).iterrows():
    rows.append([s.cost, s.init if s.init != "reduced" else f"reduced ({s.scale:g}π/√L)", s.n,
                 ci(s.ratio, s.ratio_lo, s.ratio_hi)])
table(["cost", "initialization", "n", "Var[init] / Var[uniform]"], rows)
g = big[(big.cost == "global") & (big.scale == 1.0)]
passes = g[g.ratio_lo >= 10]
w(f"**H3 variance criterion (global cost, n ≥ 10):** "
  + ("met by " + ", ".join(f"{r.init} at n = {r.n}" for _, r in passes.iterrows()) if len(passes)
     else f"not met. Largest ratio: {g.ratio.max():.2f}× ({g.loc[g.ratio.idxmax(), 'init']}, "
          f"n = {int(g.loc[g.ratio.idxmax(), 'n'])}); every 95% upper bound is below 10×."))
w("")

# ------------------------------------------------------------------ H3 training
tf = pd.read_csv(R / "task_final.csv")
w(f"## H3, part 2: teacher-state training ({TASK_ITERS} iterations, Adam, 10 seeds)")
w("")
w(f"Success = C_G ≤ {TASK_TARGET} (fidelity ≥ 0.9), measured exactly, for either training cost. "
  f"Median iterations to success counts unsuccessful runs as > {TASK_ITERS}; it is reported as "
  f"'> {TASK_ITERS}' when fewer than half of the seeds succeed. Primary mode: {TASK_SHOTS}-shot "
  "parameter-shift gradients (fixed before any training result was seen); exact gradients are the control.")
w("")


def med_iters(s):
    v = s.iters_to_target.fillna(np.inf).to_numpy()
    m = np.median(v)
    return f"> {TASK_ITERS}" if not np.isfinite(m) else f"{m:.0f}"


for mode in ("shots", "exact"):
    w(f"**{'Shot-noise' if mode == 'shots' else 'Exact'} gradients**")
    w("")
    rows = []
    for n in sorted(tf[tf["mode"] == mode].n.unique()):      # shot runs stop at n = 10
        for cost in ("global", "local"):
            r = [n, cost]
            for init in ("uniform", "reduced", "identity"):
                s = tf[(tf.n == n) & (tf.cost == cost) & (tf.init == init) & (tf["mode"] == mode)]
                r.append(f"{int(s.reached.sum())}/{len(s)}, {med_iters(s)}, {np.median(s.C_G_final):.3f}")
            rows.append(r)
    table(["n", "training cost", "uniform", "reduced", "identity"], rows)
w("Each cell: seeds reaching the target, median iterations to target, median final C_G.")
w("")

# ------------------------------------------------------------------ H4 runs C/D
se = pd.read_csv(R / "shot_ext_final.csv")
sb = pd.read_csv(results_dir(1) / "shot_final.csv")             # Run B (Week 1)
w("## H4 continued: Run C (n = 10) and Run D (fewer shots, n = 8)")
w("")
w("Same protocol as Run B (Brier loss, Adam 0.05, batch 32, 30 epochs, 5 folds × 3 seeds). "
  "'true / used' = exact gradient norm divided by the norm of the gradient the optimizer received, "
  "averaged over training. Run D's 1024-shot and exact rows are Run B's.")
w("")
rows = []
for (run, n, shots), s in se.groupby(["run", "n", "shots_train"]):
    for readout in ("global", "local"):
        t = s[s.readout == readout]
        rows.append([run, n, shots or "exact", readout,
                     f"{t.exact_auc.mean():.3f} ± {t.exact_auc.std():.3f}",
                     f"{t.exact_bacc.mean():.3f} ± {t.exact_bacc.std():.3f}",
                     f"{t.shots_auc.mean():.3f} ± {t.shots_auc.std():.3f}",
                     f"{t.signal_ratio.mean():.2f}" if shots else "1"])
for mode in ("shots", "exact"):
    for readout in ("global", "local"):
        t = sb[(sb.n == RUN_D_N) & (sb["mode"] == mode) & (sb.readout == readout)]
        rows.append(["B", RUN_D_N, SHOTS_TRAIN if mode == "shots" else "exact", readout,
                     f"{t.exact_auc.mean():.3f} ± {t.exact_auc.std():.3f}",
                     f"{t.exact_bacc.mean():.3f} ± {t.exact_bacc.std():.3f}",
                     f"{t.shots_auc.mean():.3f} ± {t.shots_auc.std():.3f}", "see Week 1"])
table(["run", "n", "training shots", "readout", "test AUC", "test bal. acc.", "AUC, 2048-shot Aer eval",
       "true / used grad. norm"], rows)
c = se[(se.run == "C") & (se.shots_train > 0)]
gC, lC = c[c.readout == "global"].exact_auc, c[c.readout == "local"].exact_auc
gap = lC.mean() - gC.mean()
cx = se[(se.run == "C") & (se.shots_train == 0)]
sd = max(gC.std(), lC.std())
w(f"**H4 at the largest n (10, 1024 shots):** local − global test AUC = {gap:+.3f}; "
  f"largest s.d. = {sd:.3f}. The curves are "
  + ("separated by more than one s.d." if abs(gap) > sd else "within one s.d. (falsifier met)")
  + f" With exact gradients the gap is {cx[cx.readout == 'local'].exact_auc.mean() - cx[cx.readout == 'global'].exact_auc.mean():+.3f}.")
w("")

# ------------------------------------------------------------------ noise
nv = pd.read_csv(R / "noise_variance.csv")
w(f"## Noise: density-matrix gradients (HEA, |0…0⟩, uniform init, 200 draws)")
w("")
w(f"Two-qubit channel strength p₂ = {NOISE_P2} after every CZ, p₂/10 after every one-qubit gate.")
w("")
rows = []
for n in sorted(nv[nv.study == "n"].n.unique()):
    s = nv[(nv.study == "n") & (nv.n == n)]
    r = [n, int(s.L.iloc[0])]
    for cost in ("global", "local"):
        for m in ("noiseless", "depolarizing", "amplitude_damping"):
            r.append(fmt(s[(s.cost == cost) & (s.model == m)].var_k.iloc[0]))
    rows.append(r)
table(["n", "L", "C_G noiseless", "C_G depol.", "C_G amp. damp.", "C_L noiseless", "C_L depol.", "C_L amp. damp."], rows)
w("Depth study (n = 6): Var averaged over parameters, and its fitted decay per layer, "
  "log Var = a − c L over L = 2…12:")
w("")
rows = []
d = nv[nv.study == "depth"]
for cost in ("global", "local"):
    for m in ("noiseless", "depolarizing", "amplitude_damping"):
        s = d[(d.cost == cost) & (d.model == m)].sort_values("L")
        s2 = s[s.L >= 2]
        slope = -np.polyfit(s2.L, np.log(s2.var_mean), 1)[0]
        rows.append([cost, m] + [fmt(v) for v in s.var_mean] + [f"{slope:.3f}"])
table(["cost", "model"] + [f"L={L}" for L in sorted(d.L.unique())] + ["c (per layer)"], rows)
w("Strength study (n = 6, L = 6): Var averaged over parameters relative to noiseless:")
w("")
p = nv[nv.study == "p"]
rows = []
for cost in ("global", "local"):
    v0 = p[(p.cost == cost) & (p.model == "noiseless")].var_mean.iloc[0]
    for m in ("depolarizing", "amplitude_damping"):
        s = p[(p.cost == cost) & (p.model == m)].sort_values("p2")
        rows.append([cost, m] + [f"{v / v0:.3f}" for v in s.var_mean])
table(["cost", "model"] + [f"p₂={x:g}" for x in sorted(p[p.model != 'noiseless'].p2.unique())], rows)

# ------------------------------------------------------------------ fake backend
fb = pd.read_csv(R / "fake_backend.csv")
w(f"## FakeFez noise model (Aer density matrix, exact probabilities incl. readout error)")
w("")
w(f"Shot floor = mean parameter-shift estimator variance for {HW_SHOTS} shots per circuit "
  "(what a hardware run at that budget adds to the measured variance).")
w("")
rows = []
for (n, k), s in fb.groupby(["n", "k"]):
    for cost in ("global", "local"):
        t = s[s.cost == cost].set_index("model")
        rows.append([n, k, cost, fmt(t.loc["noiseless", "var"]), fmt(t.loc["fake_no_readout", "var"]),
                     ci(t.loc["fake", "var"], t.loc["fake", "var_lo"], t.loc["fake", "var_hi"]),
                     fmt(t.loc["fake", "shot_floor"]),
                     f"{t.loc['fake', 'var'] / t.loc['fake', 'shot_floor']:.1f}"])
table(["n", "parameter", "cost", "Var noiseless", "Var FakeFez (no readout err.)", "Var FakeFez",
       f"shot floor ({HW_SHOTS})", "Var / floor"], rows)

(R / "week2_summary.md").write_text("\n".join(out), encoding="utf-8")
print("wrote week2/results/week2_summary.md")
